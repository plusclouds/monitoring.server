-- Views for Grafana (F07). Dashboards query these, never the base tables,
-- so the storage layout can change. They run with the owner's rights and
-- show every tenant: the monitor_grafana role is for the platform operator.
CREATE VIEW metric_series_v AS
SELECT s.id AS series_id, s.tenant_id, g.device_id, d.name AS device_name, g.source_id AS check_id,
       c.name AS check_name, g.plugin, g.object_key AS object, s.name, s.unit, s.kind, s.labels,
       rc.name AS retention_class
  FROM metric_series s
  JOIN metric_groups g ON g.id = s.group_id
  JOIN retention_classes rc ON rc.id = g.retention_class
  LEFT JOIN devices d ON d.id = g.device_id
  LEFT JOIN checks c ON c.id = g.source_id;

CREATE VIEW metrics_raw AS
SELECT m.ts AS time, s.id AS series_id, s.tenant_id, g.device_id, g.source_id AS check_id,
       g.object_key AS object, s.name, s.unit, m.vals[s.slot] AS value
  FROM metric_samples m
  JOIN metric_groups g ON g.id = m.group_id AND g.retention_class = m.retention_class
  JOIN metric_series s ON s.group_id = g.id
 WHERE m.vals[s.slot] <> 'NaN'::float8;

CREATE VIEW metrics_5m AS
SELECT r.ts AS time, s.id AS series_id, s.tenant_id, g.device_id, g.source_id AS check_id,
       g.object_key AS object, s.name, s.unit, r.min, r.max, r.sum / r.count AS avg, r.sum, r.count
  FROM metric_rollup_5m r
  JOIN metric_series s ON s.id = r.series_id
  JOIN metric_groups g ON g.id = s.group_id;

CREATE VIEW metrics_1h AS
SELECT r.ts AS time, s.id AS series_id, s.tenant_id, g.device_id, g.source_id AS check_id,
       g.object_key AS object, s.name, s.unit, r.min, r.max, r.sum / r.count AS avg, r.sum, r.count
  FROM metric_rollup_1h r
  JOIN metric_series s ON s.id = r.series_id
  JOIN metric_groups g ON g.id = s.group_id;

CREATE VIEW devices_v AS
SELECT d.id, d.tenant_id, t.name AS tenant_name, d.name, d.type, d.address, d.site_id, st.name AS site_name,
       d.parent_id, d.tags,
       CASE
           WHEN hc.id IS NULL THEN 'unmonitored'
           WHEN NOT hc.enabled THEN 'disabled'
           WHEN hs.check_id IS NULL OR hs.status = 'UNKNOWN' THEN 'unknown'
           WHEN hs.phase = 'PROBLEM' THEN 'down'
           ELSE 'up' END AS availability,
       (SELECT count(*) FROM incidents i WHERE i.device_id = d.id AND i.status <> 'resolved') AS open_incidents
  FROM devices d
  JOIN tenants t ON t.id = d.tenant_id
  LEFT JOIN sites st ON st.id = d.site_id
  LEFT JOIN checks hc ON hc.device_id = d.id AND hc.is_host_check
  LEFT JOIN check_state hs ON hs.check_id = hc.id;

CREATE VIEW check_states_v AS
SELECT c.id AS check_id, c.tenant_id, c.device_id, d.name AS device_name, c.name, c.plugin, c.enabled,
       c.interval_seconds, s.phase, s.status, s.since, s.last_result_at, s.last_status, s.last_output, s.incident_id
  FROM checks c
  JOIN devices d ON d.id = c.device_id
  LEFT JOIN check_state s ON s.check_id = c.id;

CREATE VIEW incidents_v AS
SELECT i.id, i.tenant_id, i.device_id, d.name AS device_name, i.check_id, c.name AS check_name, i.severity,
       i.status, i.summary, i.flapping, i.opened_at, i.acknowledged_at, i.resolved_at, i.resolved_by,
       coalesce(i.resolved_at, now()) - i.opened_at AS duration
  FROM incidents i
  LEFT JOIN devices d ON d.id = i.device_id
  LEFT JOIN checks c ON c.id = i.check_id;

